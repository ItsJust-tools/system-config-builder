import type { SystemService } from "./types";

/** Convert a service environment record KEY=VALUE entries into .env file lines. */
function envLinesFromService(
  serviceName: string,
  environment: Record<string, string>,
): string[] {
  const lines: string[] = [];
  for (const [key, value] of Object.entries(environment)) {
    const defaultValue = value === "" ? "" : value;
    lines.push(`${key}=${defaultValue}`);
  }
  if (lines.length > 0) {
    lines.unshift(`# ${serviceName}`);
  }
  return lines;
}

/** Collect environment variable entries (with service grouping) from all services. */
export function collectEnvEntries(
  services: SystemService[],
): { name: string; environment: Record<string, string> }[] {
  return services
    .filter((s) => s.environment && Object.keys(s.environment).length > 0)
    .map((s) => ({
      name: s.name,
      environment: s.environment as Record<string, string>,
    }));
}

/**
 * Generate the content of a `.env.example` file from service environment variables.
 * Returns null when there are no environment variables at all.
 */
export function generateEnvFile(
  title: string,
  services: SystemService[],
): string | null {
  const grouped = collectEnvEntries(services);
  if (grouped.length === 0) return null;

  const lines: string[] = [
    `# ${title} — .env example`,
    "# Generated by System Config Builder",
    "# Copy this file to .env and fill in real values.",
    "",
  ];

  for (const { name, environment } of grouped) {
    lines.push(...envLinesFromService(name, environment));
    lines.push("");
  }

  return lines.join("\n");
}

/**
 * Check whether any service defines environment variables.
 */
export function hasEnvironmentVariables(services: SystemService[]): boolean {
  return services.some(
    (s) => s.environment && Object.keys(s.environment).length > 0,
  );
}
